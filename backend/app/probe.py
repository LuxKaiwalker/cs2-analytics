"""Development tooling: dump everything awpy actually returns for a demo.

Run before freezing the normalized schema or writing analytics. The point is to
replace assumptions about column names, weapon strings and dataset availability
with observed facts, and to measure parse time and peak memory so the upload cap
and the worker's memory limit are chosen rather than guessed.

Output is written to ``docs/awpy-probe.md``.
"""

from __future__ import annotations

import io
import resource
import time
from pathlib import Path

import awpy
import polars as pl
from awpy import Demo

# Datasets we expect to use. Probed individually so one failure does not hide the rest.
_DATASETS = [
    "rounds",
    "kills",
    "damages",
    "bomb",
    "grenades",
    "fires",
    "smokes",
    "shots",
    "blinds",
    "item_events",
    "round_economy",
    "players",
    "chat",
    "stats",
]


def _peak_rss_mb() -> float:
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024


def _frame_report(out: io.StringIO, name: str, frame: pl.DataFrame) -> None:
    out.write(f"\n### `{name}` — {frame.height} rows, {frame.width} cols\n\n")
    out.write("| column | dtype | nulls | sample |\n|---|---|---|---|\n")
    for col in frame.columns:
        series = frame[col]
        sample = ""
        non_null = series.drop_nulls()
        if non_null.len():
            sample = str(non_null[0])[:40].replace("|", "\\|")
        out.write(f"| `{col}` | {series.dtype} | {series.null_count()} | `{sample}` |\n")


def probe(demo_path: Path) -> str:
    """Parse ``demo_path`` and return a Markdown report."""
    out = io.StringIO()
    out.write("# awpy probe report\n\n")
    out.write("Generated by `python -m app.cli probe <demo>`. Observed facts, not assumptions.\n\n")

    out.write(f"- awpy version: **{awpy.__version__}**\n")
    out.write(f"- polars version: **{pl.__version__}**\n")
    out.write(f"- demo: `{demo_path.name}` ({demo_path.stat().st_size / 1e6:.1f} MB)\n")

    t0 = time.perf_counter()
    demo = Demo(demo_path)
    out.write(f"- open time: {time.perf_counter() - t0:.3f}s (construction is lazy)\n")

    # --- header / timing ----------------------------------------------------
    out.write("\n## Header\n\n```python\n")
    for key, value in sorted(demo.header.items()):
        out.write(f"{key!r}: {value!r}\n")
    out.write("```\n")
    out.write(f"\n- `tick_rate` = **{demo.tick_rate}**\n")
    out.write(f"- `tick_to_seconds(10000)` = {demo.tick_to_seconds(10000):.4f}\n")

    # --- game events present ------------------------------------------------
    t0 = time.perf_counter()
    counts = demo.events.counts
    out.write(
        f"\n## Game events ({len(counts)} distinct, scan {time.perf_counter() - t0:.2f}s)\n\n"
    )
    out.write("| event | count |\n|---|---|\n")
    for name, count in sorted(counts.items(), key=lambda kv: -kv[1]):
        out.write(f"| `{name}` | {count} |\n")
    for critical in (
        "player_blind",
        "flashbang_detonate",
        "round_start",
        "round_end",
        "item_purchase",
        "player_team",
        "player_death",
        "player_hurt",
    ):
        state = "PRESENT" if critical in counts else "ABSENT"
        out.write(f"\n- `{critical}`: **{state}**")
    out.write("\n")

    # --- datasets -----------------------------------------------------------
    out.write("\n## Datasets\n")
    frames: dict[str, pl.DataFrame] = {}
    timings: dict[str, float] = {}
    for name in _DATASETS:
        t0 = time.perf_counter()
        try:
            frame = getattr(demo, name)
        except Exception as exc:  # noqa: BLE001 - a probe reports failures, never raises
            out.write(f"\n### `{name}` — FAILED: {type(exc).__name__}: {exc}\n")
            continue
        timings[name] = time.perf_counter() - t0
        frames[name] = frame
        _frame_report(out, name, frame)
        out.write(f"\n_decode {timings[name]:.2f}s_\n")

    # --- the specific open questions ---------------------------------------
    out.write("\n## Open questions\n\n")

    kills = frames.get("kills")
    if kills is not None:
        has_af = "assistedflash" in kills.columns
        out.write(f"1. **`kills.assistedflash` present?** {'YES' if has_af else 'NO'}\n")
        out.write(f"   - full columns: `{kills.columns}`\n")
        out.write(
            f"2. **distinct `kills.weapon`** ({kills['weapon'].n_unique()}): "
            f"`{sorted(kills['weapon'].unique().to_list())}`\n"
        )

    damages = frames.get("damages")
    if damages is not None:
        out.write(
            f"3. **distinct `damages.weapon`** ({damages['weapon'].n_unique()}): "
            f"`{sorted(damages['weapon'].unique().to_list())}`\n"
        )
        low, high = damages["dmg_health"].min(), damages["dmg_health"].max()
        out.write(f"   - `dmg_health` range: {low!r}..{high!r}\n")
        out.write(f"   - rows where `health_post` is null: {damages['health_post'].null_count()}\n")

    blinds = frames.get("blinds")
    if blinds is not None:
        out.write(f"4. **`blinds` populated?** {blinds.height} rows\n")

    grenades = frames.get("grenades")
    if grenades is not None and grenades.height:
        distinct = (
            grenades.select("thrower_steamid", "type", "entity_id", "entity_serial").unique().height
        )
        out.write(
            f"5. **`grenades`**: {grenades.height} trajectory rows -> "
            f"{distinct} distinct projectiles\n"
        )
        out.write(f"   - types: `{sorted(grenades['type'].unique().to_list())}`\n")

    players = frames.get("players")
    if players is not None:
        out.write(
            f"6. **`players`**: {players.height} rows; "
            f"steamid==0 rows: {(players['steamid'] == 0).sum()}; "
            f"team_clan_name nulls: {players['team_clan_name'].null_count()}\n"
        )

    # snapshots at round freeze-ends: the roster signal the design depends on
    rounds = frames.get("rounds")
    if rounds is not None and rounds.height:
        ticks = [
            int(t)
            for t in rounds.select(pl.coalesce("freeze_end_tick", "start_tick").alias("t"))["t"]
            .drop_nulls()
            .to_list()
        ]
        t0 = time.perf_counter()
        try:
            snap = demo.snapshots(ticks=ticks)
        except Exception as exc:  # noqa: BLE001 - report and continue
            out.write(f"7. **`snapshots(ticks=[...])` FAILED**: {type(exc).__name__}: {exc}\n")
        else:
            out.write(
                f"7. **`snapshots(ticks=<{len(ticks)} freeze-end ticks>)`**: "
                f"{snap.height} rows in {time.perf_counter() - t0:.2f}s\n"
            )
            out.write(f"   - columns: `{snap.columns}`\n")
            out.write(
                f"   - distinct ticks returned: {snap['tick'].n_unique()} "
                f"of {len(set(ticks))} requested\n"
            )
            out.write(
                f"   - players per tick: {snap.group_by('tick').len()['len'].to_list()[:8]}\n"
            )
            if "side" in snap.columns:
                out.write(f"   - `side` values: `{sorted(snap['side'].unique().to_list())}`\n")
            if "health" in snap.columns:
                low, high = snap["health"].min(), snap["health"].max()
                out.write(f"   - `health` at freeze end: min={low!r} max={high!r}\n")
            _frame_report(out, "snapshots(freeze_end_ticks)", snap.head(3))

    # --- convars ------------------------------------------------------------
    try:
        convars = demo.convars
    except Exception as exc:  # noqa: BLE001 - report and continue
        out.write(f"\n8. **`convars` FAILED**: {exc}\n")
    else:
        interesting = {
            k: v
            for k, v in convars.items()
            if any(s in k for s in ("maxrounds", "overtime", "freezetime", "teamname", "roundtime"))
        }
        out.write(f"\n8. **`convars`**: {len(convars)} total; relevant: `{interesting}`\n")

    # --- reference scoreboard ----------------------------------------------
    stats = frames.get("stats")
    if stats is not None and stats.height:
        out.write("\n## awpy `stats` (reference scoreboard to cross-check against)\n\n```\n")
        with pl.Config(tbl_rows=-1, tbl_cols=-1, tbl_width_chars=400):
            out.write(
                str(
                    stats.select(
                        [
                            c
                            for c in (
                                "name",
                                "rounds_played",
                                "kills",
                                "deaths",
                                "assists",
                                "flash_assists",
                                "headshot_kills",
                                "headshot_pct",
                                "adr",
                                "kast",
                                "opening_kills",
                                "opening_deaths",
                                "traded_deaths",
                                "utility_damage",
                                "flashes_thrown",
                                "enemies_flashed",
                            )
                            if c in stats.columns
                        ]
                    )
                )
            )
        out.write("\n```\n")

    out.write("\n## Resource use\n\n")
    out.write(
        f"- peak RSS after loading every dataset: **{_peak_rss_mb():.0f} MB** "
        f"for a {demo_path.stat().st_size / 1e6:.0f} MB demo "
        f"(ratio {_peak_rss_mb() / (demo_path.stat().st_size / 1e6):.1f}x)\n"
    )
    out.write(f"- decode timings: `{ {k: round(v, 2) for k, v in timings.items()} }`\n")
    return out.getvalue()
